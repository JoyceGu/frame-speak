// Bundles the view into one self-contained HTML string (no external requests),
// then writes it as a JS module the worker imports, plus a local demo page.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";

const r = await build({
  entryPoints: [new URL("../src/view/main.js", import.meta.url).pathname],
  bundle: true, format: "iife", minify: true, write: false, target: "es2020", platform: "browser",
  alias: { "@modelcontextprotocol/ext-apps": "@modelcontextprotocol/ext-apps/app-with-deps" },
});
const js = r.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const tpl = readFileSync(new URL("../src/view/template.html", import.meta.url), "utf8");
const html = tpl.replace("/*__BUNDLE__*/", () => js);
const hash = createHash("sha256").update(html).digest("hex").slice(0, 10);

mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/generated/view.js", import.meta.url),
  `// Generated by scripts/build-view.mjs. Do not edit.\nexport const VIEW_HASH = ${JSON.stringify(hash)};\nexport const VIEW_HTML = ${JSON.stringify(html)};\n`);

// Demo page: the same view, fed sample data directly (open dist/demo.html?demo).
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
const { guideFromDeck } = await import("../src/shared/guide.js");
const { DECK } = await import("../src/shared/data.js");
const demo = {
  guide: guideFromDeck("en", "work", 0),
  zh: guideFromDeck("zh", "life", 1),
  chart: (type, lang = "en") => guideFromDeck(lang, "chart", DECK.chart.findIndex(r => r[3].type === type)),
};
const charts = Object.fromEntries(["line","bar","hbar","stacked","donut","funnel","waterfall","diverge","scatter","hist","heatmap"].map(t => [t, demo.chart(t)]));
const feedback = {
  lang: "en", topic: demo.guide.topic, framework: demo.guide.framework,
  scores: { structure: 4, clarity: 3, vocabulary: 3, naturalness: 4 },
  summary: "Clear structure and a concrete example. Tighten the opening and use fewer filler words.",
  strengths: ["You led with your point.", "The example had a real number in it."],
  fixes: [{ original: "I think maybe we can do it", better: "I'd suggest we try it", why: "More confident and direct." }],
  translations: [{ from: "复盘", to: "look back on it / do a retro" }],
  polished: "I'd **come down firmly** on remote-first. It **frees up** two hours a day, and our last launch shipped a week early.",
  speech: ["I'd come *down‿on* the side / of *remote-first*.", "It frees‿up *two hours* a day."],
  vocab: [{ word: "free up", pos: "phrasal verb", meaning: "make time or resources available", example: "Async updates free up our mornings." }],
  next: "Open with one sentence that answers the question.",
};
const demoJs = `window.addEventListener("load",()=>{const D=${JSON.stringify({ guide: demo.guide, zh: demo.zh, charts, feedback })};
const q=new URLSearchParams(location.search), v=q.get("view")||"guide";
if(v==="feedback") __fs.showFeedback(D.feedback); else if(v==="zh") __fs.showGuide(D.zh); else if(D.charts[v]) __fs.showGuide(D.charts[v]); else __fs.showGuide(D.guide);});`;
writeFileSync(new URL("../dist/demo.html", import.meta.url), html.replace("</body>", `<script>${demoJs}</script></body>`));
console.log(`view: ${(html.length / 1024).toFixed(1)} KB, hash ${hash}`);
