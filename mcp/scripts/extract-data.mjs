// Pulls the content tables out of the web app (../index.html) so the MCP server
// and the web app share one source of truth. Run after editing index.html.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const NAMES = ["FRAMEWORKS", "FW_PH", "DECK", "CHART_TYPES", "DATA_STEP_PH", "CHART_ORDER", "MONTHS"];
const html = readFileSync(new URL("../../index.html", import.meta.url), "utf8");
const lines = html.split("\n");

function block(name) {
  const start = lines.findIndex(l => l.startsWith(`const ${name} =`));
  if (start < 0) throw new Error(`const ${name} not found in index.html`);
  if (lines[start].trimEnd().endsWith(";")) return lines[start];
  const end = lines.findIndex((l, i) => i > start && /^};\s*$/.test(l));
  return lines.slice(start, end + 1).join("\n");
}

const src = NAMES.map(block).join("\n") + `\n;({${NAMES.join(",")}})`;
const data = vm.runInNewContext(src);
const out = "// Generated by scripts/extract-data.mjs from ../index.html. Do not edit by hand.\n" +
  NAMES.map(n => `export const ${n} = ${JSON.stringify(data[n])};`).join("\n") + "\n";
writeFileSync(new URL("../src/shared/data.js", import.meta.url), out);
console.log(`data.js: ${NAMES.map(n => n + (Array.isArray(data[n]) ? `[${data[n].length}]` : `{${Object.keys(data[n]).length}}`)).join(" ")}`);
